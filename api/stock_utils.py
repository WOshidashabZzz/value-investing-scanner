def map_sector_by_name(stock_name: str) -> str | None:
    """根据股票名称关键词映射到一级板块。"""
    if not stock_name:
        return None

    for sector, keywords in SECTOR_KEYWORDS.items():
        for keyword in keywords:
            if keyword in stock_name:
                return sector

    return None
